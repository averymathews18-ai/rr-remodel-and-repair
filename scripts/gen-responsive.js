/* Generate responsive WebP rungs for every referenced image.
   Fixed-aspect surfaces (sliders 4:3, Process 16:9, About 4:3) get the
   object-cover crop BAKED IN, so we stop shipping rows the browser discards.
   Masonry tiles keep their natural aspect. Masters are never modified. */
const sharp = require('sharp');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', 'public');
const SRC = path.join(__dirname, '..', 'masters');
const OUT = path.join(ROOT, 'img');

// [file, variantName, aspect(null=natural), widths, quality]
const JOBS = [
  // hero backdrop — opacity .22 behind a scrim, crush it hard
  ['gallery/cherry-after.jpg', 'bd', null, [640, 1080, 1600], 42],

  // before/after sliders — always rendered in a 4:3 box
  ['gallery/progress-2.jpg', 'c43', 4 / 3, [480, 768, 1080, 1440], 76],
  ['gallery/work-cherry-1.jpg', 'c43', 4 / 3, [480, 768, 1080, 1440], 76],
  ['gallery/white-before.jpg', 'c43', 4 / 3, [480, 768, 1080, 1440], 76],
  ['gallery/white-after.jpg', 'c43', 4 / 3, [480, 768, 1080, 1440], 76],
  ['gallery/work-gray-2.jpg', 'c43', 4 / 3, [480, 768, 1080, 1440], 76],
  ['gallery/gray-staged-wide.jpg', 'c43', 4 / 3, [480, 768, 1080, 1440], 76],

  // About figure — 4:3 box
  ['gallery/gray-after.jpg', 'c43', 4 / 3, [480, 768, 1080], 78],
  // Process figure — 16:9 box
  ['gallery/progress-1.jpg', 'c169', 16 / 9, [480, 768, 1080, 1440], 78],

  // Recent Work masonry — natural aspect, column width ~400px max
  ...[
    'cherry-after', 'work-gray-4', 'work-cherry-3', 'work-gray-3',
    'work-gray-5', 'work-cherry-2', 'work-gray-1', 'work-gray-6',
  ].map(n => [`gallery/${n}.jpg`, 't', null, [400, 640, 900], 76]),

  // brand
  ['brand/logo.webp', 'l', null, [320, 480, 700], 86],
  ['brand/logo-mark.webp', 'l', null, [140, 220, 340], 88],
];

(async () => {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });

  for (const [rel, variant, aspect, widths, quality] of JOBS) {
    const src = path.join(SRC, rel.replace(/^gallery\//, 'gallery/').replace(/^brand\//, ''));
    if (!fs.existsSync(src)) { console.log('MISSING', rel); continue; }
    const base = path.basename(rel).replace(/\.(jpe?g|png|webp)$/i, '');
    const meta = await sharp(src).metadata();

    for (const w of widths) {
      if (w > meta.width * 1.02) continue;
      const dest = path.join(OUT, `${base}--${variant}-${w}.webp`);
      let pipe = sharp(src);
      pipe = aspect
        ? pipe.resize(w, Math.round(w / aspect), { fit: 'cover', position: 'centre' })
        : pipe.resize(w);
      await pipe.webp({ quality, effort: 6 }).toFile(dest);
      console.log(String(Math.round(fs.statSync(dest).size / 1024)).padStart(5) + 'K', path.basename(dest));
    }
  }

  // Write the manifest the <Img> component reads: rungs + the intrinsic
  // size of the largest rung, so every image can reserve its exact box
  // before it loads (no layout shift, no zero-height reveal races).
  const manifest = {};
  for (const f of fs.readdirSync(OUT)) {
    const m = f.match(/^(.+?)--([a-z0-9]+)-(\d+)\.webp$/);
    if (!m) continue;
    const key = `${m[1]}--${m[2]}`;
    (manifest[key] = manifest[key] || { rungs: [] }).rungs.push(+m[3]);
  }
  for (const key of Object.keys(manifest)) {
    manifest[key].rungs.sort((a, b) => a - b);
    const biggest = manifest[key].rungs[manifest[key].rungs.length - 1];
    const meta = await sharp(path.join(OUT, `${key}-${biggest}.webp`)).metadata();
    manifest[key].w = meta.width;
    manifest[key].h = meta.height;
  }
  fs.writeFileSync(
    path.join(__dirname, '..', 'src', 'lib', 'img-manifest.ts'),
    '/* AUTO-GENERATED by scripts/gen-responsive.js — do not edit by hand.\n' +
    '   "<base>--<variant>" -> available width rungs + intrinsic size. */\n' +
    'export type ImgEntry = { rungs: number[]; w: number; h: number };\n' +
    'export const IMG_RUNGS: Record<string, ImgEntry> = ' +
    JSON.stringify(manifest, null, 2) + ';\n',
  );

  const files = fs.readdirSync(OUT);
  const total = files.reduce((a, f) => a + fs.statSync(path.join(OUT, f)).size, 0);
  console.log('\nrungs:', files.length, 'files,', Math.round(total / 1024) + 'K total');
  console.log('manifest:', Object.keys(manifest).length, 'entries');
})();
